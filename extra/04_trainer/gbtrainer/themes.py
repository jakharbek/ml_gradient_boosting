"""Сюжеты тетрадей: объект, целевая величина, три бинарных признака и масштаб чисел.

Каждый сюжет даёт три признака: уровни 1–4 берут первые два, уровень 5 — все три. Порядок
значений признака важен: второе значение прибавляет к целевой величине свой вклад
(«полный привод дороже переднего»), так что случайные данные остаются правдоподобными.

Масштаб чисел (база, шаг сетки, вклады, шум) подобран так, чтобы среднее было целым, а суммы
в группах считались в уме — как в тетрадях № 2–7, по которым сделан генератор.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class FeatureDef:
    name: str
    levels: tuple[str, str]  # (без вклада, со вкладом)


@dataclass(frozen=True)
class Theme:
    key: str
    title: str  # для списков: «Пекарни — выпечка за день»
    object: str  # заголовок колонки объектов: «Пекарня»
    each: str  # «каждой пекарне» — для текста этапа D
    target: str  # заголовок колонки y: «Реальная выпечка yᵢ, кг»
    quantity: str  # «выпечка за день» — для «Устройства данных»
    features: tuple[FeatureDef, FeatureDef, FeatureDef]
    base: tuple[int, int, int]  # база: от, до, шаг сетки
    effect: tuple[int, int, int]  # самый слабый вклад: от, до, шаг сетки
    noise: tuple[int, int]  # амплитуда шума: от, до


def _f(name: str, low: str, high: str) -> FeatureDef:
    return FeatureDef(name, (low, high))


